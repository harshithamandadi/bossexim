/**
 * Generates src/lib/world-dots.ts: a grid of [longitude, latitude] points that
 * fall on land, used to draw the dotted world map and the rotating globe.
 *   node scripts/generate-world-dots.mjs
 * Land outlines: Natural Earth 1:50m (public domain), via the world-atlas package.
 */
import { geoContains } from "d3-geo";
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";

const STEP = 2; // degrees between dots
const SOUTH = -56; // skip Antarctica
const NORTH = 76;

const topology = JSON.parse(readFileSync(new URL("../node_modules/world-atlas/land-50m.json", import.meta.url), "utf8"));
const land = feature(topology, topology.objects.land);

const dots = [];
for (let lat = NORTH; lat >= SOUTH; lat -= STEP) {
  for (let lon = -180; lon < 180; lon += STEP) {
    if (geoContains(land, [lon, lat])) dots.push([Math.round(lon * 10) / 10, Math.round(lat * 10) / 10]);
  }
}

const body = `/* Generated by scripts/generate-world-dots.mjs — do not edit by hand. */
/** [longitude, latitude] points on land, ${STEP}° apart (Natural Earth 1:50m). */
export const WORLD_DOTS: readonly (readonly [number, number])[] = ${JSON.stringify(dots)};
`;
writeFileSync(new URL("../src/lib/world-dots.ts", import.meta.url), body);
console.log(`${dots.length} dots written`);
